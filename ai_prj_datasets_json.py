def value_to_text(value):
    """Converte valores de datasets/JSON para texto."""
    if value is None:
        return ""

    if isinstance(value, str):
        return value

    if isinstance(value, (int, float, bool)):
        return str(value)

    if isinstance(value, dict):
        parts = []
        used_fields = set()

        # Prioriza campos conhecidos.
        for field in TEXT_FIELDS:
            if field in value:
                item = value_to_text(value[field])
                if item.strip():
                    parts.append(item)
                used_fields.add(field)

        # Aproveita também outros campos textuais.
        for key, item in value.items():
            if key in used_fields:
                continue

            converted = value_to_text(item)
            if converted.strip():
                parts.append(converted)

        return "\n".join(parts)

    if isinstance(value, (list, tuple)):
        return "\n".join(
            item
            for item in (value_to_text(v) for v in value)
            if item.strip()
        )

    return str(value)


def load_json_text(path):
    """Carrega JSON ou JSONL."""
    import json

    with open(path, "r", encoding="utf-8") as f:
        raw = f.read()

    if not raw.strip():
        raise ValueError(f"O arquivo '{path}' está vazio.")

    # Tenta JSON tradicional primeiro.
    try:
        data = json.loads(raw)
        return value_to_text(data)
    except json.JSONDecodeError:
        pass

    # Se não for JSON tradicional, tenta JSONL.
    records = []
    for line_number, line in enumerate(raw.splitlines(), 1):
        line = line.strip()

        if not line:
            continue

        try:
            records.append(json.loads(line))
        except json.JSONDecodeError as exc:
            raise ValueError(
                f"JSONL inválido na linha {line_number}: {exc}"
            ) from exc

    if not records:
        raise ValueError(f"Nenhum registro encontrado em '{path}'.")

    return value_to_text(records)


def load_huggingface_text(dataset_name):
    """Carrega um dataset Hugging Face e transforma seus registros em texto."""
    from datasets import load_dataset

    ds = load_dataset(dataset_name)

    texts = []

    # DatasetDict normalmente possui splits como train/validation/test.
    if hasattr(ds, "keys") and not hasattr(ds, "features"):
        splits = list(ds.keys())

        for split_name in splits:
            split_dataset = ds[split_name]

            for record in split_dataset:
                item = value_to_text(record)

                if item.strip():
                    texts.append(item)

    else:
        for record in ds:
            item = value_to_text(record)

            if item.strip():
                texts.append(item)

    if not texts:
        raise ValueError(
            f"O dataset '{dataset_name}' não contém dados textuais utilizáveis."
        )

    return "\n\n".join(texts)


def load_text_data(source_type, source):
    """Carrega TXT, JSON, JSONL ou Hugging Face."""
    source_type = source_type.lower().strip()

    if source_type == "auto":
        if os.path.isfile(source):
            extension = os.path.splitext(source)[1].lower()

            if extension in (".json", ".jsonl"):
                source_type = "json"
            elif extension == ".txt":
                source_type = "txt"
            else:
                raise ValueError(
                    "Extensão não suportada no modo auto. "
                    "Use .txt, .json ou .jsonl."
                )
        else:
            # Se não for arquivo local, assume Hugging Face.
            source_type = "huggingface"

    if source_type == "txt":
        if not os.path.isfile(source):
            raise FileNotFoundError(
                f"Arquivo TXT não encontrado: {source}"
            )

        with open(source, "r", encoding="utf-8") as f:
            text = f.read()

    elif source_type == "json":
        if not os.path.isfile(source):
            raise FileNotFoundError(
                f"Arquivo JSON/JSONL não encontrado: {source}"
            )

        text = load_json_text(source)

    elif source_type in ("huggingface", "dataset", "datasets"):
        text = load_huggingface_text(source)

    else:
        raise ValueError(
            f"DATA_SOURCE_TYPE inválido: '{source_type}'. "
            "Use 'auto', 'txt', 'json' ou 'huggingface'."
        )

    if not text or not text.strip():
        raise ValueError("A fonte de dados não contém texto utilizável.")

    return text


