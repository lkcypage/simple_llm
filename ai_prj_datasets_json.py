@torch.no_grad()
def estimate_loss():

    model.eval()

    results = {}

    for split_name in ["train", "val"]:

        losses = torch.zeros(EVAL_ITERS)

        for k in range(EVAL_ITERS):

            x, y = get_batch(split_name)

            _, loss = model(x, y)

            losses[k] = loss.item()

        results[split_name] = losses.mean().item()

    model.train()

    return results

