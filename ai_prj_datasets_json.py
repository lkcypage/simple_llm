class MiniGPT(nn.Module):

    def __init__(
        self,
        vocab_size,
        block_size,
        n_embd,
        n_head,
        n_layer,
        dropout
    ):
        super().__init__()

        self.block_size = block_size

        # Embedding dos tokens
        self.token_embedding = nn.Embedding(
            vocab_size,
            n_embd
        )

        # Embedding das posições
        self.position_embedding = nn.Embedding(
            block_size,
            n_embd
        )

        self.dropout = nn.Dropout(dropout)

        self.blocks = nn.ModuleList([
            TransformerBlock(
                n_embd,
                n_head,
                dropout
            )
            for _ in range(n_layer)
        ])

        self.ln_final = nn.LayerNorm(n_embd)

        # Converte representação para logits
        self.lm_head = nn.Linear(
            n_embd,
            vocab_size,
            bias=False
        )

        # Weight tying:
        # embedding e saída compartilham pesos.
        self.lm_head.weight = self.token_embedding.weight

        self.apply(self._init_weights)

    def _init_weights(self, module):

        if isinstance(module, nn.Linear):
            nn.init.normal_(
                module.weight,
                mean=0.0,
                std=0.02
            )

            if module.bias is not None:
                nn.init.zeros_(module.bias)

        elif isinstance(module, nn.Embedding):
            nn.init.normal_(
                module.weight,
                mean=0.0,
                std=0.02
            )

    def forward(self, idx, targets=None):

        B, T = idx.shape

        if T > self.block_size:
            raise ValueError(
                f"Sequência maior que BLOCK_SIZE={self.block_size}"
            )

        positions = torch.arange(
            0,
            T,
            device=idx.device
        )

        token_emb = self.token_embedding(idx)

        position_emb = self.position_embedding(
            positions
        )

        x = token_emb + position_emb

        x = self.dropout(x)

        for block in self.blocks:
            x = block(x)

        x = self.ln_final(x)

        logits = self.lm_head(x)

        loss = None

        if targets is not None:

            B, T, C = logits.shape

            logits_flat = logits.view(
                B * T,
                C
            )

            targets_flat = targets.view(
                B * T
            )

            loss = F.cross_entropy(
                logits_flat,
                targets_flat
            )

        return logits, loss

    @torch.no_grad()
    def generate(
        self,
        idx,
        max_new_tokens=200,
        temperature=0.8,
        top_k=50
    ):

        self.eval()

        for _ in range(max_new_tokens):

            # Mantém somente o contexto suportado
            idx_cond = idx[:, -self.block_size:]

            logits, _ = self(idx_cond)

            # Último token
            logits = logits[:, -1, :]

            # Temperature
            logits = logits / temperature

            # Top-K sampling
            if top_k is not None:

                values, _ = torch.topk(
                    logits,
                    min(top_k, logits.size(-1))
                )

                threshold = values[:, [-1]]

                logits = torch.where(
                    logits < threshold,
                    torch.full_like(
                        logits,
                        float("-inf")
                    ),
                    logits
                )

            probabilities = F.softmax(
                logits,
                dim=-1
            )

            next_token = torch.multinomial(
                probabilities,
                num_samples=1
            )

            idx = torch.cat(
                (idx, next_token),
                dim=1
            )

        return idx

